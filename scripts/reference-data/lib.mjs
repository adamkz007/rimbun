import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

export const REPO_ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
export const SEED_OUTPUT_PATH = path.join(REPO_ROOT, "supabase/seed/001_reference_data.sql");
export const MANIFEST_OUTPUT_PATH = path.join(
  REPO_ROOT,
  "scripts/reference-data/manifest.json"
);

export async function ensureParentDirectory(filePath) {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
}

export async function downloadToTempFile(url, fileName) {
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`Failed to download ${url}: ${response.status} ${response.statusText}`);
  }

  const outputPath = path.join(os.tmpdir(), fileName);
  const arrayBuffer = await response.arrayBuffer();
  await fs.writeFile(outputPath, Buffer.from(arrayBuffer));
  return outputPath;
}

export async function unzipTextFile(zipPath, entryPattern) {
  const { stdout: listOutput } = await execFileAsync("unzip", ["-Z1", zipPath], {
    encoding: "utf8",
  });

  const entryName = listOutput
    .split("\n")
    .map((entry) => entry.trim())
    .find((entry) => entryPattern.test(entry));

  if (!entryName) {
    throw new Error(`No archive entry matched ${entryPattern} in ${zipPath}`);
  }

  const { stdout } = await execFileAsync("unzip", ["-p", zipPath, entryName], {
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 64,
  });

  return stdout;
}

export function parseCsv(text) {
  const rows = [];
  let currentCell = "";
  let currentRow = [];
  let inQuotes = false;

  const pushCell = () => {
    currentRow.push(currentCell);
    currentCell = "";
  };

  const pushRow = () => {
    if (currentRow.length === 1 && currentRow[0] === "") {
      currentRow = [];
      return;
    }

    rows.push(currentRow);
    currentRow = [];
  };

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const nextChar = text[index + 1];

    if (char === '"') {
      if (inQuotes && nextChar === '"') {
        currentCell += '"';
        index += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (char === "," && !inQuotes) {
      pushCell();
      continue;
    }

    if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && nextChar === "\n") {
        index += 1;
      }
      pushCell();
      pushRow();
      continue;
    }

    currentCell += char;
  }

  if (currentCell.length > 0 || currentRow.length > 0) {
    pushCell();
    pushRow();
  }

  if (rows.length === 0) {
    return [];
  }

  const [header, ...records] = rows;
  return records.map((record) =>
    Object.fromEntries(header.map((column, index) => [column, record[index] ?? ""]))
  );
}

export function normalizeWhitespace(value) {
  return value.replace(/\s+/g, " ").trim();
}

export function titleCase(value) {
  return normalizeWhitespace(value)
    .toLowerCase()
    .replace(/\b([a-z])/g, (match) => match.toUpperCase())
    .replace(/\bHcl\b/g, "HCl")
    .replace(/\bMr\b/g, "MR")
    .replace(/\bXl\b/g, "XL")
    .replace(/\bSr\b/g, "SR")
    .replace(/\bEr\b/g, "ER")
    .replace(/\bMd\b/g, "MD")
    .replace(/\bMdi\b/g, "MDI")
    .replace(/\bIi\b/g, "II");
}

function toCopyValue(value) {
  if (value === null || value === undefined || value === "") {
    return "\\N";
  }

  return String(value)
    .replace(/\\/g, "\\\\")
    .replace(/\t/g, "\\t")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r");
}

export function renderCopyBlock(tableName, columns, rows) {
  const body = rows
    .map((row) => columns.map((column) => toCopyValue(row[column])).join("\t"))
    .join("\n");

  return `COPY ${tableName} (${columns.join(", ")}) FROM stdin;\n${body}\n\\\\.\n`;
}

export async function writeReferenceSeedFile({ icd10Rows, drugRows, metadata }) {
  const contents = [
    "-- Generated by scripts/reference-data/build-all.mjs",
    `-- Generated at ${new Date().toISOString()}`,
    `-- ICD-10 source: ${metadata.icd10.sourceUrl}`,
    `-- ICD-10 rows: ${metadata.icd10.rowCount}`,
    `-- Drug source: ${metadata.drugs.sourceUrl}`,
    `-- Drug rows: ${metadata.drugs.rowCount}`,
    "",
    renderCopyBlock("icd10_codes", ["code", "description", "category"], icd10Rows),
    renderCopyBlock(
      "drugs",
      ["name", "generic_name", "formulation", "strength", "manufacturer", "is_controlled"],
      drugRows
    ),
  ].join("\n");

  await ensureParentDirectory(SEED_OUTPUT_PATH);
  await fs.writeFile(SEED_OUTPUT_PATH, contents, "utf8");
}

export async function writeManifestFile(manifest) {
  await ensureParentDirectory(MANIFEST_OUTPUT_PATH);
  await fs.writeFile(MANIFEST_OUTPUT_PATH, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
}
